defmodule Minga.Conformance.FocusCorpusTest do
  use ExUnit.Case, async: true

  alias Mix.Tasks.Conformance.FocusScenarios
  alias Minga.Frontend.Adapter.GUI.Caches
  alias Minga.Frontend.Adapter.GUI.FocusOwnerEncoder
  alias MingaEditor.FocusOwner
  alias MingaEditor.Session.State, as: Workspace
  alias MingaEditor.State, as: EditorState

  @root Path.expand("corpus", __DIR__)

  test "focus corpus is generated by the real encoder and enabled on both consumers" do
    index = @root |> Path.join("index.json") |> File.read!() |> JSON.decode!()
    entries = Enum.filter(index["transcripts"], &(&1["category"] == "focus" and &1["go"] == true))
    assert length(entries) == length(FocusScenarios.scenarios())

    for generated <- FocusScenarios.build_all() do
      entry = Enum.find(entries, &(&1["name"] == generated["name"]))
      assert entry["swift"] == true
      assert entry["go"] == true
      actual = @root |> Path.join(entry["file"]) |> File.read!() |> JSON.decode!()
      assert actual == generated, "stale focus corpus: run mix conformance.gen"
    end
  end

  for {name, actions} <- FocusScenarios.scenarios() do
    @name name
    @actions actions
    test "#{name} retains the BEAM owner on unchanged frames and refreshes it on reattach" do
      transcript = @root |> Path.join("focus/#{@name}.json") |> File.read!() |> JSON.decode!()

      Enum.zip(@actions, transcript["steps"])
      |> Enum.reduce({%EditorState{workspace: %Workspace{}}, %Caches{}, nil}, fn
        {{action, keyframe?}, step}, {state, caches, committed_owner} ->
          state = FocusScenarios.transition(state, action)
          owner = FocusOwner.derive(state)
          assert step["expect"]["focus_target"] == FocusScenarios.expectation(owner)
          assert step["reset_frontend"] == (action == :reattach)
          committed_owner = if step["reset_frontend"], do: nil, else: committed_owner
          caches = if keyframe?, do: %Caches{}, else: caches
          {encoded, caches} = FocusOwnerEncoder.encode(owner, caches)
          commands = split(Base.decode64!(step["payload_base64"]), step["command_sizes"])
          focus_commands = Enum.filter(commands, &match?(<<0xAA, _::binary>>, &1))
          assert focus_commands == if(encoded, do: [encoded], else: [])
          committed_owner = List.first(focus_commands) || committed_owner
          {expected_owner, _caches} = FocusOwnerEncoder.encode(owner, %Caches{})
          assert committed_owner == expected_owner
          {state, caches, committed_owner}
      end)
    end
  end

  defp split(<<>>, []), do: []

  defp split(bytes, [size | sizes]) do
    <<command::binary-size(^size), rest::binary>> = bytes
    [command | split(rest, sizes)]
  end
end
